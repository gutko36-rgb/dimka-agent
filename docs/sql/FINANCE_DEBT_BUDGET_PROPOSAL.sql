-- Debt ledger, atomic debt repayment, monthly budgets and distribution weights.
-- The main Telegram bot remains the only writer and must still verify telegram_id.
-- No data is inserted into the live project by this file.

begin;

create table if not exists public.finance_debts (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null,
    direction text not null
        check (direction in ('owed_by_me', 'owed_to_me')),
    counterparty text not null
        check (length(btrim(counterparty)) between 1 and 120),
    title text not null
        check (length(btrim(title)) between 1 and 180),
    amount numeric(14,2) not null
        check (amount > 0),
    amount_remaining numeric(14,2) not null
        check (amount_remaining >= 0 and amount_remaining <= amount),
    due_date date null,
    status text not null default 'open'
        check (status in ('open', 'paid', 'cancelled')),
    note text null,
    source_update_id bigint null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint finance_debts_amount_state_check
        check (
            (status = 'paid' and amount_remaining = 0)
            or (status = 'open' and amount_remaining > 0)
            or status = 'cancelled'
        )
);

create unique index if not exists finance_debts_id_telegram_id_uidx
    on public.finance_debts (id, telegram_id);
create unique index if not exists finance_debts_owner_source_update_uidx
    on public.finance_debts (telegram_id, source_update_id);
create index if not exists finance_debts_owner_status_due_idx
    on public.finance_debts (telegram_id, status, due_date);

create unique index if not exists finance_transactions_id_telegram_id_uidx
    on public.finance_transactions (id, telegram_id);

create table if not exists public.finance_debt_payments (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null,
    debt_id bigint not null,
    amount numeric(14,2) not null check (amount > 0),
    payment_date date not null default current_date,
    finance_transaction_id bigint null,
    source_update_id bigint not null,
    created_at timestamptz not null default now(),
    constraint finance_debt_payments_owner_update_unique
        unique (telegram_id, source_update_id),
    constraint finance_debt_payments_debt_owner_fk
        foreign key (debt_id, telegram_id)
        references public.finance_debts (id, telegram_id)
        on delete cascade,
    constraint finance_debt_payments_transaction_owner_fk
        foreign key (finance_transaction_id, telegram_id)
        references public.finance_transactions (id, telegram_id)
        on delete set null (finance_transaction_id)
);

create index if not exists finance_debt_payments_owner_debt_date_idx
    on public.finance_debt_payments (telegram_id, debt_id, payment_date);

create table if not exists public.finance_budgets (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null,
    period_month date not null
        check (extract(day from period_month) = 1),
    category text not null
        check (length(btrim(category)) between 1 and 80),
    limit_amount numeric(14,2) not null
        check (limit_amount >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint finance_budgets_owner_month_category_unique
        unique (telegram_id, period_month, category)
);

create table if not exists public.finance_budget_weights (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null,
    category text not null
        check (length(btrim(category)) between 1 and 80),
    weight numeric(14,4) not null
        check (weight >= 0),
    updated_at timestamptz not null default now(),
    constraint finance_budget_weights_owner_category_unique
        unique (telegram_id, category)
);

alter table public.finance_debts enable row level security;
alter table public.finance_debt_payments enable row level security;
alter table public.finance_budgets enable row level security;
alter table public.finance_budget_weights enable row level security;

revoke all on table public.finance_debts from public, anon, authenticated;
revoke all on table public.finance_debt_payments from public, anon, authenticated;
revoke all on table public.finance_budgets from public, anon, authenticated;
revoke all on table public.finance_budget_weights from public, anon, authenticated;

grant all on table public.finance_debts to service_role;
grant all on table public.finance_debt_payments to service_role;
grant all on table public.finance_budgets to service_role;
grant all on table public.finance_budget_weights to service_role;

grant usage, select on sequence
    public.finance_debts_id_seq,
    public.finance_debt_payments_id_seq,
    public.finance_budgets_id_seq,
    public.finance_budget_weights_id_seq
to service_role;

create or replace function public.record_finance_debt_payment(
    p_telegram_id bigint,
    p_debt_id bigint,
    p_amount numeric,
    p_payment_date date,
    p_source_update_id bigint
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    v_debt public.finance_debts%rowtype;
    v_existing public.finance_debt_payments%rowtype;
    v_transaction_id bigint;
    v_payment_id bigint;
    v_remaining numeric(14,2);
    v_kind text;
    v_category text;
    v_note text;
begin
    if p_telegram_id is null or p_debt_id is null or p_source_update_id is null then
        raise exception 'telegram_id, debt_id and source_update_id are required'
            using errcode = '22023';
    end if;
    if p_amount is null or p_amount <= 0 then
        raise exception 'payment amount must be greater than zero'
            using errcode = '22023';
    end if;
    if p_payment_date is null then
        raise exception 'payment_date is required' using errcode = '22023';
    end if;

    select *
      into v_existing
      from public.finance_debt_payments
     where telegram_id = p_telegram_id
       and source_update_id = p_source_update_id;

    if found then
        if v_existing.debt_id <> p_debt_id
           or v_existing.amount <> p_amount
           or v_existing.payment_date <> p_payment_date then
            raise exception 'source update id was already used for a different debt payment'
                using errcode = '23505';
        end if;
        select amount_remaining, status
          into v_remaining, v_kind
          from public.finance_debts
         where id = v_existing.debt_id
           and telegram_id = p_telegram_id;
        return jsonb_build_object(
            'duplicate', true,
            'payment_id', v_existing.id,
            'transaction_id', v_existing.finance_transaction_id,
            'amount_remaining', v_remaining,
            'status', v_kind
        );
    end if;

    select *
      into v_debt
      from public.finance_debts
     where id = p_debt_id
       and telegram_id = p_telegram_id
     for update;

    if not found then
        raise exception 'debt not found for this owner' using errcode = 'P0002';
    end if;
    if v_debt.status <> 'open' then
        raise exception 'debt is not open' using errcode = '55000';
    end if;
    if p_amount > v_debt.amount_remaining then
        raise exception 'payment exceeds remaining debt' using errcode = '22003';
    end if;

    if v_debt.direction = 'owed_by_me' then
        v_kind := 'expense';
        v_category := 'Погашение долга';
    else
        v_kind := 'income';
        v_category := 'Возврат долга';
    end if;
    v_note := format('%s: %s', v_debt.counterparty, v_debt.title);

    insert into public.finance_transactions (
        telegram_id, kind, amount, category, note, tx_date,
        source_update_id, source_item_index
    )
    values (
        p_telegram_id, v_kind, p_amount, v_category, v_note, p_payment_date,
        p_source_update_id, 0
    )
    on conflict (telegram_id, source_update_id, source_item_index)
        where source_update_id is not null
    do nothing
    returning id into v_transaction_id;

    if v_transaction_id is null then
        select id
          into v_transaction_id
          from public.finance_transactions
         where telegram_id = p_telegram_id
           and source_update_id = p_source_update_id
           and source_item_index = 0
           and kind = v_kind
           and amount = p_amount
           and category = v_category
           and tx_date = p_payment_date;
    end if;
    if v_transaction_id is null then
        raise exception 'could not create or recover finance transaction';
    end if;

    v_remaining := round(v_debt.amount_remaining - p_amount, 2);

    insert into public.finance_debt_payments (
        telegram_id, debt_id, amount, payment_date,
        finance_transaction_id, source_update_id
    )
    values (
        p_telegram_id, p_debt_id, p_amount, p_payment_date,
        v_transaction_id, p_source_update_id
    )
    on conflict (telegram_id, source_update_id) do nothing
    returning id into v_payment_id;

    if v_payment_id is null then
        select *
          into v_existing
          from public.finance_debt_payments
         where telegram_id = p_telegram_id
           and source_update_id = p_source_update_id;
        if v_existing.debt_id <> p_debt_id
           or v_existing.amount <> p_amount
           or v_existing.payment_date <> p_payment_date then
            raise exception 'source update id was already used for a different debt payment'
                using errcode = '23505';
        end if;
        v_payment_id := v_existing.id;
        return jsonb_build_object(
            'duplicate', true,
            'payment_id', v_payment_id,
            'transaction_id', v_transaction_id,
            'amount_remaining', v_debt.amount_remaining,
            'status', v_debt.status
        );
    end if;

    update public.finance_debts
       set amount_remaining = v_remaining,
           status = case when v_remaining = 0 then 'paid' else 'open' end,
           updated_at = now()
     where id = p_debt_id
       and telegram_id = p_telegram_id;

    return jsonb_build_object(
        'duplicate', false,
        'payment_id', v_payment_id,
        'transaction_id', v_transaction_id,
        'amount_remaining', v_remaining,
        'status', case when v_remaining = 0 then 'paid' else 'open' end
    );
end;
$$;

revoke all on function public.record_finance_debt_payment(bigint, bigint, numeric, date, bigint)
    from public, anon, authenticated;
grant execute on function public.record_finance_debt_payment(bigint, bigint, numeric, date, bigint)
    to service_role;

comment on table public.finance_debts is
    'Owner-scoped debt ledger. Direction owed_by_me is an outgoing liability; owed_to_me is a receivable.';
comment on table public.finance_debt_payments is
    'Immutable debt repayment ledger linked to the corresponding cash-flow transaction.';
comment on table public.finance_budgets is
    'Monthly spending limits per owner and category.';
comment on table public.finance_budget_weights is
    'Owner-defined weights used by the optional money distribution planner.';

commit;
