    public.lifestyle_goals_id_seq,
    public.lifestyle_goal_updates_id_seq,
    public.lifestyle_habits_id_seq,
    public.lifestyle_habit_logs_id_seq
to service_role;

revoke all on function public.record_lifestyle_goal_progress(bigint, bigint, numeric, text, bigint)
    from public, anon, authenticated;
grant execute on function public.record_lifestyle_goal_progress(bigint, bigint, numeric, text, bigint)
    to service_role;

comment on table public.lifestyle_goals is
    'Owner-scoped personal goals with explicit progress and status.';
comment on table public.lifestyle_goal_updates is
    'Append-only progress history for goals.';
comment on table public.lifestyle_habits is
    'Owner-scoped habits with weekly target frequency.';
comment on table public.lifestyle_habit_logs is
    'One daily completion or skip record per owner and habit.';

