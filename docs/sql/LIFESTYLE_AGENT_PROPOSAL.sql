-- Dedicated owner-scoped goals, habits and history.
-- Apply only to a disposable Supabase development branch after review.
-- Existing daily_logs, surveys, profiles and memories are not modified.

begin;

create table if not exists public.lifestyle_goals (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null check (telegram_id > 0),
    title text not null check (length(btrim(title)) between 1 and 180),
    description text null check (description is null or length(description) <= 2000),
    target_date date null,
    status text not null default 'active'
        check (status in ('active', 'completed', 'paused', 'cancelled')),
    progress numeric(5,2) not null default 0
        check (progress between 0 and 100),
    source_update_id bigint null check (source_update_id is null or source_update_id > 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint lifestyle_goals_owner_source_unique unique (telegram_id, source_update_id),
    constraint lifestyle_goals_id_owner_unique unique (id, telegram_id)
);

create index if not exists lifestyle_goals_owner_status_idx
    on public.lifestyle_goals (telegram_id, status, target_date);

create table if not exists public.lifestyle_goal_updates (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null check (telegram_id > 0),
    goal_id bigint not null,
    progress numeric(5,2) not null check (progress between 0 and 100),
    note text null check (note is null or length(note) <= 2000),
    source_update_id bigint not null check (source_update_id > 0),
    created_at timestamptz not null default now(),
    constraint lifestyle_goal_updates_owner_source_unique unique (telegram_id, source_update_id),
    constraint lifestyle_goal_updates_goal_owner_fk
        foreign key (goal_id, telegram_id)
        references public.lifestyle_goals (id, telegram_id)
        on delete cascade
);

create index if not exists lifestyle_goal_updates_owner_goal_date_idx
    on public.lifestyle_goal_updates (telegram_id, goal_id, created_at desc);

create table if not exists public.lifestyle_habits (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null check (telegram_id > 0),
    title text not null check (length(btrim(title)) between 1 and 180),
    description text null check (description is null or length(description) <= 2000),
    target_per_week smallint not null default 7 check (target_per_week between 1 and 7),
    is_active boolean not null default true,
    start_date date not null default current_date,
    end_date date null,
    source_update_id bigint null check (source_update_id is null or source_update_id > 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint lifestyle_habits_owner_source_unique unique (telegram_id, source_update_id),
    constraint lifestyle_habits_id_owner_unique unique (id, telegram_id),
    constraint lifestyle_habits_date_range_check check (end_date is null or end_date >= start_date)
);

create index if not exists lifestyle_habits_owner_active_idx
    on public.lifestyle_habits (telegram_id, is_active, title);

create table if not exists public.lifestyle_habit_logs (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null check (telegram_id > 0),
    habit_id bigint not null,
    log_date date not null default current_date,
    status text not null check (status in ('done', 'skipped')),
    note text null check (note is null or length(note) <= 1000),
    source_update_id bigint not null,
    created_at timestamptz not null default now(),
    constraint lifestyle_habit_logs_owner_source_unique unique (telegram_id, source_update_id),
    constraint lifestyle_habit_logs_habit_owner_fk
        foreign key (habit_id, telegram_id)
        references public.lifestyle_habits (id, telegram_id)
        on delete cascade
);

create index if not exists lifestyle_habit_logs_owner_date_idx
    on public.lifestyle_habit_logs (telegram_id, log_date desc, habit_id, created_at desc);

create index if not exists lifestyle_habit_logs_owner_habit_date_idx
    on public.lifestyle_habit_logs (telegram_id, habit_id, log_date, created_at desc);

-- Atomic, owner-scoped progress update with idempotency and audit history.
create or replace function public.record_lifestyle_goal_progress(
    p_telegram_id bigint,
    p_goal_id bigint,
    p_progress numeric,
    p_note text,
    p_source_update_id bigint
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    v_goal public.lifestyle_goals%rowtype;
    v_existing public.lifestyle_goal_updates%rowtype;
    v_update_id bigint;
    v_status text;
begin
    if p_telegram_id is null or p_telegram_id <= 0
       or p_goal_id is null or p_goal_id <= 0
       or p_source_update_id is null or p_source_update_id <= 0
       or p_progress is null or p_progress < 0 or p_progress > 100 then
        raise exception 'invalid goal progress arguments' using errcode = '22023';
    end if;

    p_progress := round(p_progress, 2);

    select * into v_existing
      from public.lifestyle_goal_updates
     where telegram_id = p_telegram_id
       and source_update_id = p_source_update_id;

    if found then
        if v_existing.goal_id <> p_goal_id
           or v_existing.progress <> p_progress
           or coalesce(v_existing.note, '') <> coalesce(p_note, '') then
            raise exception 'source update id was reused for another goal update'
                using errcode = '23505';
        end if;
        select status into v_status
          from public.lifestyle_goals
         where id = p_goal_id and telegram_id = p_telegram_id;
        return jsonb_build_object('duplicate', true, 'goal_id', p_goal_id,
                                  'progress', v_existing.progress, 'status', v_status);
    end if;

    select * into v_goal
      from public.lifestyle_goals
     where id = p_goal_id and telegram_id = p_telegram_id
     for update;

    if not found then
        raise exception 'goal not found for this owner' using errcode = 'P0002';
    end if;
    if v_goal.status in ('cancelled', 'paused') then
        raise exception 'goal is not active' using errcode = '55000';
    end if;

    insert into public.lifestyle_goal_updates
        (telegram_id, goal_id, progress, note, source_update_id)
    values
        (p_telegram_id, p_goal_id, p_progress, p_note, p_source_update_id)
    returning id into v_update_id;

    update public.lifestyle_goals
       set progress = p_progress,
           status = case when p_progress = 100 then 'completed' else 'active' end,
           updated_at = now()
     where id = p_goal_id and telegram_id = p_telegram_id;

    return jsonb_build_object(
        'duplicate', false,
        'update_id', v_update_id,
        'goal_id', p_goal_id,
        'progress', p_progress,
        'status', case when p_progress = 100 then 'completed' else 'active' end
    );
end;
$$;

